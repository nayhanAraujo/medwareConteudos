-- Comentário de normalidade por variável + referência (não por faixa).
-- Ex.: VR_ESPESSURA_PAREDE_LIVRE_VD → "≤ 5" no estudo ASE, sem duplicar em M/F/zonas.

CREATE TABLE NORMALIDADECOMENTARIO (
    CODNORMALIDADECOMENTARIO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODVARIAVEL INTEGER NOT NULL,
    CODREFERENCIA INTEGER NOT NULL,
    TEXTO VARCHAR(500) NOT NULL,
    CODUSUARIO INTEGER,
    DTHRULTMODIFICACAO TIMESTAMP,
    CONSTRAINT PK_NORMALIDADECOMENTARIO PRIMARY KEY (CODNORMALIDADECOMENTARIO),
    CONSTRAINT UQ_NORMALIDADECOMENTARIO_VAR_REF UNIQUE (CODVARIAVEL, CODREFERENCIA)
);

ALTER TABLE NORMALIDADECOMENTARIO ADD CONSTRAINT FK_NCOM_CODVARIAVEL
    FOREIGN KEY (CODVARIAVEL) REFERENCES VARIAVEIS (CODVARIAVEL)
    ON DELETE CASCADE;

ALTER TABLE NORMALIDADECOMENTARIO ADD CONSTRAINT FK_NCOM_CODREFERENCIA
    FOREIGN KEY (CODREFERENCIA) REFERENCES REFERENCIA (CODREFERENCIA)
    ON DELETE CASCADE;
