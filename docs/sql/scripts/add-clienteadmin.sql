-- DTHR* em UTC. CNPJ normalizado suporta números/letras (12 posições + 2 DVs).
-- CLIENTEADMIN é satélite 1:1; CLIENTEADMINCONSULTA guarda confirmações curtas e autoria.
-- CODUSUARIO segue autoria histórica do módulo, sem FK para permitir retenção do histórico.
-- CK_CLIADMCONS_CONSUMIDA abrevia CLIENTEADMINCONSULTA para respeitar 31 caracteres.
SET SQL DIALECT 3;
SET AUTODDL OFF;
SET BAIL ON;
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
 IF(NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='CLIENTEADMIN')) THEN
  EXECUTE STATEMENT 'CREATE TABLE CLIENTEADMIN(
   CODCLIENTE INTEGER NOT NULL, CNPJ CHAR(14) CHARACTER SET ASCII NOT NULL,
   DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, CODUSUARIO INTEGER NOT NULL,
   DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_CLIENTEADMIN PRIMARY KEY(CODCLIENTE),
   CONSTRAINT UNQ_CLIENTEADMIN_CNPJ UNIQUE(CNPJ),
   CONSTRAINT FK_CLIENTEADMIN_CODCLIENTE FOREIGN KEY(CODCLIENTE) REFERENCES CLIENTES(CODCLIENTE))';
 IF(NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='CLIENTEADMINCONSULTA')) THEN
  EXECUTE STATEMENT 'CREATE TABLE CLIENTEADMINCONSULTA(
   CODCLIENTEADMINCONSULTA CHAR(36) CHARACTER SET ASCII NOT NULL, CODUSUARIO INTEGER NOT NULL,
   DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL,
   DTHREXPIRACAO TIMESTAMP NOT NULL, CONSUMIDA SMALLINT DEFAULT 0 NOT NULL,
   CONSTRAINT PK_CLIENTEADMINCONSULTA PRIMARY KEY(CODCLIENTEADMINCONSULTA),
   CONSTRAINT CK_CLIADMCONS_CONSUMIDA CHECK(CONSUMIDA IN (0,1)))';
END^
