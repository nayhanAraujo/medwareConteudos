-- Padrões de normalidade por cliente (snapshot do catálogo ou 100% customizado).
-- Não altera NORMALIDADE / NORMALIDADECOMENTARIO globais.

CREATE TABLE CLIENTESPADRAONORMALIDADE (
    CODPADRAO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODCLIENTE INTEGER NOT NULL,
    NOME VARCHAR(200) NOT NULL,
    CODIGO VARCHAR(50) NOT NULL,
    CODREFERENCIA INTEGER,
    PADRAOVIGENTE SMALLINT DEFAULT 0 NOT NULL,
    ATIVO SMALLINT DEFAULT 1 NOT NULL,
    DESCRICAO VARCHAR(500),
    CODUSUARIO INTEGER,
    DTHRULTMODIFICACAO TIMESTAMP,
    CONSTRAINT PK_CLIENTESPADRAONORMALIDADE PRIMARY KEY (CODPADRAO),
    CONSTRAINT UQ_PADRAO_CLIENTE_CODIGO UNIQUE (CODCLIENTE, CODIGO),
    CONSTRAINT CHK_PADRAO_VIGENTE CHECK (PADRAOVIGENTE IN (0, 1)),
    CONSTRAINT CHK_PADRAO_ATIVO CHECK (ATIVO IN (0, 1))
);

ALTER TABLE CLIENTESPADRAONORMALIDADE ADD CONSTRAINT FK_PADRAO_CODCLIENTE
    FOREIGN KEY (CODCLIENTE) REFERENCES CLIENTES (CODCLIENTE)
    ON DELETE CASCADE;

ALTER TABLE CLIENTESPADRAONORMALIDADE ADD CONSTRAINT FK_PADRAO_CODREFERENCIA
    FOREIGN KEY (CODREFERENCIA) REFERENCES REFERENCIA (CODREFERENCIA)
    ON DELETE SET NULL;

CREATE TABLE PADRAONORMALIDADEFAIXA (
    CODFAIXA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODPADRAO INTEGER NOT NULL,
    CODVARIAVEL INTEGER NOT NULL,
    CODCLASSIFICACAO INTEGER,
    SEXO CHAR(1) NOT NULL,
    VALORMIN DECIMAL(18, 6),
    VALORMAX DECIMAL(18, 6),
    IDADE_MIN INTEGER,
    IDADE_MAX INTEGER,
    PAGINA_REFERENCIA DECIMAL(18, 6),
    CODUSUARIO INTEGER,
    DTHRULTMODIFICACAO TIMESTAMP,
    CONSTRAINT PK_PADRAONORMALIDADEFAIXA PRIMARY KEY (CODFAIXA),
    CONSTRAINT CHK_PADRAOFAIXA_SEXO CHECK (SEXO IN ('M', 'F', 'A'))
);

ALTER TABLE PADRAONORMALIDADEFAIXA ADD CONSTRAINT FK_PADRAOFAIXA_CODPADRAO
    FOREIGN KEY (CODPADRAO) REFERENCES CLIENTESPADRAONORMALIDADE (CODPADRAO)
    ON DELETE CASCADE;

ALTER TABLE PADRAONORMALIDADEFAIXA ADD CONSTRAINT FK_PADRAOFAIXA_CODVARIAVEL
    FOREIGN KEY (CODVARIAVEL) REFERENCES VARIAVEIS (CODVARIAVEL)
    ON DELETE CASCADE;

ALTER TABLE PADRAONORMALIDADEFAIXA ADD CONSTRAINT FK_PADRAOFAIXA_CODCLASSIFICACAO
    FOREIGN KEY (CODCLASSIFICACAO) REFERENCES CLASSIFICACOES (CODCLASSIFICACAO)
    ON DELETE SET NULL;

CREATE TABLE PADRAONORMALIDADECOMENTARIO (
    CODPADRAOCOMENTARIO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODPADRAO INTEGER NOT NULL,
    CODVARIAVEL INTEGER NOT NULL,
    TEXTO VARCHAR(500) NOT NULL,
    CODUSUARIO INTEGER,
    DTHRULTMODIFICACAO TIMESTAMP,
    CONSTRAINT PK_PADRAONORMALIDADECOMENTARIO PRIMARY KEY (CODPADRAOCOMENTARIO),
    CONSTRAINT UQ_PADRAOCOM_PADRAO_VAR UNIQUE (CODPADRAO, CODVARIAVEL)
);

ALTER TABLE PADRAONORMALIDADECOMENTARIO ADD CONSTRAINT FK_PADRAOCOM_CODPADRAO
    FOREIGN KEY (CODPADRAO) REFERENCES CLIENTESPADRAONORMALIDADE (CODPADRAO)
    ON DELETE CASCADE;

ALTER TABLE PADRAONORMALIDADECOMENTARIO ADD CONSTRAINT FK_PADRAOCOM_CODVARIAVEL
    FOREIGN KEY (CODVARIAVEL) REFERENCES VARIAVEIS (CODVARIAVEL)
    ON DELETE CASCADE;
