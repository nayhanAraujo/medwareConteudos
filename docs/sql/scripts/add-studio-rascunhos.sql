-- Execute pelo migrador StudioDraftSchema. Separador preserva corpos de triggers.
-- UTC em todos os TIMESTAMP. SR=StudioRascunho, SV=StudioRevisao, SP=StudioPublicacao.
-- @statement
CREATE TABLE STUDIORASCUNHO (
 CODRASCUNHO CHAR(36) CHARACTER SET ASCII NOT NULL,
 CODUSUARIO INTEGER NOT NULL, REVISAO INTEGER DEFAULT 0 NOT NULL,
 NOME VARCHAR(120) CHARACTER SET UTF8 NOT NULL,
 ARQUIVADO SMALLINT DEFAULT 0 NOT NULL,
 DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
 DTHRCRIACAO TIMESTAMP NOT NULL, DTHRULTMODIFICACAO TIMESTAMP NOT NULL,
 CONSTRAINT PK_STUDIORASCUNHO PRIMARY KEY(CODRASCUNHO),
 CONSTRAINT FK_SR_CODUSUARIO FOREIGN KEY(CODUSUARIO) REFERENCES USUARIO(CODUSUARIO),
 CONSTRAINT CK_SR_REVISAO CHECK(REVISAO >= 0),
 CONSTRAINT CK_SR_ARQUIVADO CHECK(ARQUIVADO IN (0,1))
)
-- @statement
CREATE INDEX IX_SR_USUARIO_DATA ON STUDIORASCUNHO(CODUSUARIO,DTHRULTMODIFICACAO)
-- @statement
CREATE TABLE STUDIOREVISAO (
 CODRASCUNHO CHAR(36) CHARACTER SET ASCII NOT NULL, NUMERO INTEGER NOT NULL,
 CODCOMANDO CHAR(36) CHARACTER SET ASCII NOT NULL, SHA256 CHAR(64) CHARACTER SET ASCII NOT NULL,
 TIPO VARCHAR(40) CHARACTER SET ASCII NOT NULL, ORIGEM VARCHAR(10) CHARACTER SET ASCII NOT NULL,
 GRUPOOPERACAO VARCHAR(100) CHARACTER SET UTF8 NOT NULL,
 DESCRICAO VARCHAR(255) CHARACTER SET UTF8 NOT NULL,
 DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
 DETALHES BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
 DTHRCRIACAO TIMESTAMP NOT NULL,
 CONSTRAINT PK_STUDIOREVISAO PRIMARY KEY(CODRASCUNHO,NUMERO),
 CONSTRAINT UNQ_SV_COMANDO UNIQUE(CODRASCUNHO,CODCOMANDO),
 CONSTRAINT FK_SV_CODRASCUNHO FOREIGN KEY(CODRASCUNHO) REFERENCES STUDIORASCUNHO(CODRASCUNHO),
 CONSTRAINT CK_SV_ORIGEM CHECK(ORIGEM IN ('manual','voz','sistema'))
)
-- @statement
CREATE TABLE STUDIOMODELOESTADO (
 CODMODELO INTEGER NOT NULL, VERSAO BIGINT DEFAULT 0 NOT NULL,
 AJUSTES BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
 CONSTRAINT PK_STUDIOMODELOESTADO PRIMARY KEY(CODMODELO),
 CONSTRAINT FK_SME_CODMODELO FOREIGN KEY(CODMODELO) REFERENCES MODELOMODOTEXTO(CODMODELO) ON DELETE CASCADE
)
-- @statement
CREATE TABLE STUDIOPUBLICACAO (
 CODPUBLICACAO CHAR(36) CHARACTER SET ASCII NOT NULL, CODUSUARIO INTEGER NOT NULL,
 CODRASCUNHO CHAR(36) CHARACTER SET ASCII, REVISAO INTEGER NOT NULL,
 CODMODELO INTEGER, VERSAOMODELO BIGINT,
 NOME VARCHAR(120) CHARACTER SET UTF8 NOT NULL,
 ESTADO VARCHAR(15) CHARACTER SET ASCII NOT NULL,
 DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
 HASHCATALOGO CHAR(64) CHARACTER SET ASCII NOT NULL,
 DTHRCRIACAO TIMESTAMP NOT NULL,
 CONSTRAINT PK_STUDIOPUBLICACAO PRIMARY KEY(CODPUBLICACAO),
 CONSTRAINT FK_SP_CODUSUARIO FOREIGN KEY(CODUSUARIO) REFERENCES USUARIO(CODUSUARIO),
 CONSTRAINT FK_SP_CODRASCUNHO FOREIGN KEY(CODRASCUNHO) REFERENCES STUDIORASCUNHO(CODRASCUNHO) ON DELETE SET NULL,
 CONSTRAINT FK_SP_CODMODELO FOREIGN KEY(CODMODELO) REFERENCES MODELOMODOTEXTO(CODMODELO) ON DELETE SET NULL,
 CONSTRAINT CK_SP_ESTADO CHECK(ESTADO IN ('pendente','publicada'))
)
-- @statement
CREATE INDEX IX_SP_USUARIO_MODELO ON STUDIOPUBLICACAO(CODUSUARIO,CODMODELO)
-- @statement
CREATE OR ALTER TRIGGER TR_STUDIO_MODELO FOR MODELOMODOTEXTO ACTIVE AFTER INSERT OR UPDATE POSITION 100 AS
BEGIN
 IF (INSERTING) THEN INSERT INTO STUDIOMODELOESTADO(CODMODELO,VERSAO) VALUES(NEW.CODMODELO,0);
 ELSE UPDATE STUDIOMODELOESTADO SET VERSAO=VERSAO+1 WHERE CODMODELO=NEW.CODMODELO;
END
-- @statement
CREATE OR ALTER TRIGGER TR_STUDIO_SECAO FOR SECAOMODOTEXTO ACTIVE BEFORE INSERT OR UPDATE OR DELETE POSITION 100 AS
BEGIN
 IF (DELETING OR UPDATING) THEN UPDATE STUDIOMODELOESTADO SET VERSAO=VERSAO+1 WHERE CODMODELO=OLD.CODMODELO;
 IF (INSERTING OR UPDATING) THEN UPDATE STUDIOMODELOESTADO SET VERSAO=VERSAO+1 WHERE CODMODELO=NEW.CODMODELO;
END
-- @statement
CREATE OR ALTER TRIGGER TR_STUDIO_ITEM FOR SECAO_VARIAVEL ACTIVE BEFORE INSERT OR UPDATE OR DELETE POSITION 100 AS
BEGIN
 IF (DELETING OR UPDATING) THEN UPDATE STUDIOMODELOESTADO SET VERSAO=VERSAO+1 WHERE CODMODELO IN (SELECT CODMODELO FROM SECAOMODOTEXTO WHERE CODSECAO=OLD.CODSECAO);
 IF (INSERTING OR UPDATING) THEN UPDATE STUDIOMODELOESTADO SET VERSAO=VERSAO+1 WHERE CODMODELO IN (SELECT CODMODELO FROM SECAOMODOTEXTO WHERE CODSECAO=NEW.CODSECAO);
END
