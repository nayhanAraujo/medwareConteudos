-- Correção do esquema inicial de orçamentos (Firebird 4/5).
-- Executar conectado ao REFERENCIAS correto, com BACKUP e API/pool parados.
-- Requer a API atualizada para os novos nomes. Não executar com a API antiga.
-- Somente esquema inicial vazio; preserva a política inicial e recusa dados comerciais.
-- Entidades sem underline; relação N:N ORCAMENTO_USUARIO; PK/FK COD*.
-- Não altera CLIENTES, USUARIO nem as tabelas de auditoria.
-- Não é idempotente. Na segunda execução recusa o esquema já corrigido.
-- Executar o arquivo completo no isql com -b (bail on error).
-- No editor SQL, respeitar SET TERM, desativar autocommit e ROLLBACK se houver erro.
-- Três transações: DDL; cópia do seed; remoção das duas tabelas antigas do seed.
-- Firebird exige confirmar o metadata antes de inserir nas tabelas recém-criadas.
-- Se uma fase falhar, não reiniciar a API nem repetir o arquivo inteiro.
-- As origens do seed só são removidas após confirmar sua cópia; concluir a fase pendente.
SET AUTODDL OFF;
CREATE EXCEPTION EX_ORC_NOMES 'Correcao recusada: confira esquema e ausencia de registros';
SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE N INTEGER;
DECLARE T VARCHAR(63);
DECLARE K VARCHAR(63);
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_PROPOSTA' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_PROPOSTA';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_ANEXO' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_ANEXO';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_ITEM' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_ITEM';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_EDITOR' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_EDITOR';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_EVENTO' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_EVENTO';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_REVISAO' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_REVISAO';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='CLIENTE_COMERCIAL' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: CLIENTE_COMERCIAL';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_CONFIG' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_CONFIG';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_POLITICA' AND RDB$VIEW_BLR IS NULL)) THEN
    EXCEPTION EX_ORC_NOMES 'Esquema inicial ausente ou parcialmente alterado: ORCAMENTO_POLITICA';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='CLIENTECOMERCIAL')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: CLIENTECOMERCIAL';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOPOLITICA')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOPOLITICA';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOCONFIG')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOCONFIG';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOPROPOSTA')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOPROPOSTA';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOREVISAO')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOREVISAO';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOITEM')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOITEM';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTO_USUARIO')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTO_USUARIO';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOEVENTO')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOEVENTO';
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOANEXO')) THEN
    EXCEPTION EX_ORC_NOMES 'Nome de destino ja existe: ORCAMENTOANEXO';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_PROPOSTA' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO_PROPOSTA';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_ANEXO' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO_ANEXO';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_ITEM' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO_ITEM';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_EDITOR' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO_EDITOR';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_EVENTO' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO_EVENTO';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_REVISAO' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO_REVISAO';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: ORCAMENTO';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM CLIENTE_COMERCIAL' INTO :N;
  IF (N <> 0) THEN EXCEPTION EX_ORC_NOMES 'Tabela possui registros: CLIENTE_COMERCIAL';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_POLITICA' INTO :N;
  IF (N <> 1) THEN EXCEPTION EX_ORC_NOMES 'Esperada somente a politica inicial';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_POLITICA WHERE ID=1 AND CODUSUARIO=0 AND MOTIVO STARTING WITH ''Referências iniciais do POP-GO-001 v1.0;''' INTO :N;
  IF (N <> 1) THEN EXCEPTION EX_ORC_NOMES 'Politica comercial personalizada: preservar e migrar separadamente';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_CONFIG' INTO :N;
  IF (N <> 1) THEN EXCEPTION EX_ORC_NOMES 'Configuracao inicial inconsistente';
  EXECUTE STATEMENT 'SELECT COUNT(*) FROM ORCAMENTO_CONFIG WHERE ID=1 AND VERSION=1' INTO :N;
  IF (N <> 1) THEN EXCEPTION EX_ORC_NOMES 'Configuracao inicial alterada';
  -- Remover explicitamente FKs do próprio módulo antes das PKs referenciadas.
  -- Dependências externas desconhecidas NÃO são removidas: devem fazer abortar.
  FOR SELECT TRIM(RDB$RELATION_NAME),TRIM(RDB$CONSTRAINT_NAME)
      FROM RDB$RELATION_CONSTRAINTS
      WHERE RDB$CONSTRAINT_TYPE='FOREIGN KEY' AND RDB$RELATION_NAME IN
        ('CLIENTE_COMERCIAL','ORCAMENTO_POLITICA','ORCAMENTO_CONFIG','ORCAMENTO_PROPOSTA',
         'ORCAMENTO_REVISAO','ORCAMENTO_ITEM','ORCAMENTO_EDITOR','ORCAMENTO_EVENTO','ORCAMENTO_ANEXO','ORCAMENTO')
      INTO :T,:K
  DO EXECUTE STATEMENT 'ALTER TABLE ' || T || ' DROP CONSTRAINT ' || K;
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO_PROPOSTA';
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO_ANEXO';
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO_ITEM';
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO_EDITOR';
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO_EVENTO';
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO_REVISAO';
  EXECUTE STATEMENT 'DROP TABLE ORCAMENTO';
  EXECUTE STATEMENT 'DROP TABLE CLIENTE_COMERCIAL';
END^
SET TERM ; ^
-- DDL em instruções separadas para disponibilizar o metadata ao próximo comando.
CREATE TABLE CLIENTECOMERCIAL (CODCLIENTE INTEGER NOT NULL, VERSAO BIGINT NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, CONSTRAINT PK_CLIENTECOMERCIAL PRIMARY KEY(CODCLIENTE), CONSTRAINT FK_CLIENTECOMERCIAL_CODCLIENTE FOREIGN KEY(CODCLIENTE) REFERENCES CLIENTES(CODCLIENTE));
CREATE TABLE ORCAMENTOPOLITICA (CODORCAMENTOPOLITICA BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, CODUSUARIO INTEGER NOT NULL, MOTIVO VARCHAR(1000) CHARACTER SET UTF8 NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORCAMENTOPOLITICA PRIMARY KEY(CODORCAMENTOPOLITICA));
CREATE TABLE ORCAMENTOCONFIG (CODORCAMENTOCONFIG INTEGER NOT NULL, VERSAO BIGINT NOT NULL, CONSTRAINT PK_ORCAMENTOCONFIG PRIMARY KEY(CODORCAMENTOCONFIG));
CREATE TABLE ORCAMENTOPROPOSTA (CODORCAMENTO BIGINT NOT NULL, REVISAO INTEGER NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, EMAIL BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, PDF BLOB SUB_TYPE BINARY NOT NULL, SHA256 VARCHAR(64) CHARACTER SET ASCII NOT NULL, VERSAOTEMPLATE VARCHAR(40) CHARACTER SET ASCII NOT NULL, CODUSUARIO INTEGER NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORC_PROPOSTA PRIMARY KEY(CODORCAMENTO,REVISAO));
CREATE TABLE ORCAMENTO (CODORCAMENTO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, CODCLIENTE INTEGER NOT NULL, REVISAO INTEGER NOT NULL, STATUS VARCHAR(30) CHARACTER SET ASCII NOT NULL, ARQUIVADO SMALLINT DEFAULT 0 NOT NULL, VERSAO BIGINT NOT NULL, DTHRULTMODIFICACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORCAMENTO PRIMARY KEY(CODORCAMENTO), CONSTRAINT FK_ORCAMENTO_CODCLIENTE FOREIGN KEY(CODCLIENTE) REFERENCES CLIENTES(CODCLIENTE));
CREATE TABLE ORCAMENTOREVISAO (CODORCAMENTO BIGINT NOT NULL, NUMERO INTEGER NOT NULL, STATUS VARCHAR(30) CHARACTER SET ASCII NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, CODUSUARIO INTEGER NOT NULL, NOMEAUTOR VARCHAR(255) CHARACTER SET UTF8 NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORC_REV PRIMARY KEY(CODORCAMENTO,NUMERO), CONSTRAINT FK_ORCAMENTOREVISAO_CODORCAMENTO FOREIGN KEY(CODORCAMENTO) REFERENCES ORCAMENTO(CODORCAMENTO));
CREATE TABLE ORCAMENTOITEM (CODORCAMENTO BIGINT NOT NULL, REVISAO INTEGER NOT NULL, POSICAO INTEGER NOT NULL, CATEGORIA VARCHAR(30) CHARACTER SET ASCII NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, VALORBRUTO NUMERIC(18,2), DESCONTO NUMERIC(18,2), VALORFINAL NUMERIC(18,2), CONSTRAINT PK_ORC_ITEM PRIMARY KEY(CODORCAMENTO,REVISAO,POSICAO), CONSTRAINT FK_ORC_ITEM_REV FOREIGN KEY(CODORCAMENTO,REVISAO) REFERENCES ORCAMENTOREVISAO(CODORCAMENTO,NUMERO));
CREATE TABLE ORCAMENTO_USUARIO (CODORCAMENTO BIGINT NOT NULL, REVISAO INTEGER NOT NULL, CODUSUARIO INTEGER NOT NULL, CONSTRAINT PK_ORC_EDITOR PRIMARY KEY(CODORCAMENTO,REVISAO,CODUSUARIO), CONSTRAINT FK_ORC_EDITOR_REV FOREIGN KEY(CODORCAMENTO,REVISAO) REFERENCES ORCAMENTOREVISAO(CODORCAMENTO,NUMERO));
CREATE TABLE ORCAMENTOEVENTO (CODORCAMENTOEVENTO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, CODORCAMENTO BIGINT NOT NULL, REVISAO INTEGER NOT NULL, ACAO VARCHAR(40) CHARACTER SET ASCII NOT NULL, STATUSANTERIOR VARCHAR(30) CHARACTER SET ASCII NOT NULL, STATUSPOSTERIOR VARCHAR(30) CHARACTER SET ASCII NOT NULL, CODUSUARIO INTEGER NOT NULL, NOMEAUTOR VARCHAR(255) CHARACTER SET UTF8 NOT NULL, MOTIVO VARCHAR(2000) CHARACTER SET UTF8 NOT NULL, REFERENCIA VARCHAR(500) CHARACTER SET UTF8 NOT NULL, DESTINO VARCHAR(500) CHARACTER SET UTF8 NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORCAMENTOEVENTO PRIMARY KEY(CODORCAMENTOEVENTO), CONSTRAINT FK_ORCAMENTOEVENTO_CODORCAMENTO FOREIGN KEY(CODORCAMENTO) REFERENCES ORCAMENTO(CODORCAMENTO));
CREATE TABLE ORCAMENTOANEXO (CODORCAMENTOANEXO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, CODORCAMENTO BIGINT NOT NULL, REVISAO INTEGER NOT NULL, NOME VARCHAR(255) CHARACTER SET UTF8 NOT NULL, MIME VARCHAR(120) CHARACTER SET ASCII NOT NULL, TAMANHO BIGINT NOT NULL, SHA256 VARCHAR(64) CHARACTER SET ASCII NOT NULL, TIPO VARCHAR(20) CHARACTER SET ASCII NOT NULL, CONTEUDO BLOB SUB_TYPE BINARY NOT NULL, CODUSUARIO INTEGER NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT FK_ORC_ANEXO_REV FOREIGN KEY(CODORCAMENTO,REVISAO) REFERENCES ORCAMENTOREVISAO(CODORCAMENTO,NUMERO), CONSTRAINT PK_ORCAMENTOANEXO PRIMARY KEY(CODORCAMENTOANEXO));
ALTER TABLE ORCAMENTOPROPOSTA ADD CONSTRAINT FK_ORC_PROP_REV FOREIGN KEY(CODORCAMENTO,REVISAO) REFERENCES ORCAMENTOREVISAO(CODORCAMENTO,NUMERO);
CREATE INDEX IX_ORC_DATA ON ORCAMENTO(DTHRULTMODIFICACAO,CODORCAMENTO);
CREATE INDEX IX_ORC_CLIENTE ON ORCAMENTO(CODCLIENTE);
CREATE INDEX IX_ORC_EVENTO ON ORCAMENTOEVENTO(CODORCAMENTO,CODORCAMENTOEVENTO);
CREATE INDEX IX_ORC_ANEXO ON ORCAMENTOANEXO(CODORCAMENTO,REVISAO);
COMMIT;
-- Fase 2: preserva a política inicial; só remove sua origem após a cópia válida.
INSERT INTO ORCAMENTOPOLITICA(CODORCAMENTOPOLITICA,DOCUMENTO,CODUSUARIO,MOTIVO,DTHRCRIACAO)
SELECT ID,DOCUMENTO,CODUSUARIO,MOTIVO,CRIADO_UTC FROM ORCAMENTO_POLITICA;
ALTER TABLE ORCAMENTOPOLITICA ALTER CODORCAMENTOPOLITICA RESTART WITH 2;
INSERT INTO ORCAMENTOCONFIG(CODORCAMENTOCONFIG,VERSAO) SELECT ID,VERSION FROM ORCAMENTO_CONFIG;
COMMIT;
-- Fase 3: remover origens somente após confirmar a cópia do seed.
DROP TABLE ORCAMENTO_CONFIG;
DROP TABLE ORCAMENTO_POLITICA;
DROP EXCEPTION EX_ORC_NOMES;
COMMIT;
SET AUTODDL ON;
-- Verificação: nenhum ID genérico e nenhum underline nas colunas do módulo.
SELECT TRIM(R.RDB$RELATION_NAME) AS TABELA,TRIM(F.RDB$FIELD_NAME) AS COLUNA
FROM RDB$RELATIONS R JOIN RDB$RELATION_FIELDS F ON F.RDB$RELATION_NAME=R.RDB$RELATION_NAME
WHERE R.RDB$RELATION_NAME STARTING WITH 'ORCAMENTO' OR R.RDB$RELATION_NAME='CLIENTECOMERCIAL'
ORDER BY R.RDB$RELATION_NAME,F.RDB$FIELD_POSITION;

