    EXECUTE STATEMENT 'ALTER TABLE ORCAMENTOANALISE ADD ETAPA VARCHAR(20) CHARACTER SET ASCII DEFAULT ''analise'' NOT NULL';
END^
SET TERM ; ^
COMMIT;
SET TERM ^ ;
EXECUTE BLOCK AS
