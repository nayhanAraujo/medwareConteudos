-- isql: usar -b -ch UTF8. Pode ser repetido; commits separam alterações de metadata.
-- FK_ORCREGRACONFIG_VERSAO abrevia ORCAMENTOREGRACONFIG por limite conservador de nomes.
-- CODANALISEORIGEM identifica o papel de origem na autorreferência; a PK já usa CODORCAMENTOANALISE.
SET AUTODDL OFF;
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOREGRAVERSAO')) THEN
    EXECUTE STATEMENT 'CREATE TABLE ORCAMENTOREGRAVERSAO(CODORCAMENTOREGRAVERSAO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, MOTIVO VARCHAR(1000) CHARACTER SET UTF8 NOT NULL, CODUSUARIO INTEGER NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORCAMENTOREGRAVERSAO PRIMARY KEY(CODORCAMENTOREGRAVERSAO))';
END^
SET TERM ; ^
COMMIT;
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='ORCAMENTOREGRACONFIG')) THEN
    EXECUTE STATEMENT 'CREATE TABLE ORCAMENTOREGRACONFIG(CODORCAMENTOREGRACONFIG INTEGER NOT NULL, CODORCAMENTOREGRAVERSAO BIGINT NOT NULL, CONSTRAINT PK_ORCAMENTOREGRACONFIG PRIMARY KEY(CODORCAMENTOREGRACONFIG), CONSTRAINT FK_ORCREGRACONFIG_VERSAO FOREIGN KEY(CODORCAMENTOREGRAVERSAO) REFERENCES ORCAMENTOREGRAVERSAO(CODORCAMENTOREGRAVERSAO))';
END^
SET TERM ; ^
COMMIT;
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
