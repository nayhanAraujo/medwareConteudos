param([string]$ClientLibrary = 'C:\Program Files\Firebird\Firebird-5.0.2\fbclient.dll')
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
$assembly = Join-Path $root 'backend/MdwConteudos.Api/bin/Release/net10.0/FirebirdSql.Data.FirebirdClient.dll'
if (!(Test-Path -LiteralPath $ClientLibrary) -or !(Test-Path -LiteralPath $assembly)) { throw 'Embedded Firebird client/provider not available. No operational database will be used.' }
Add-Type -Path $assembly
$fixtureDirectory = Join-Path ([IO.Path]::GetTempPath()) ('studio-schema-' + [Guid]::NewGuid().ToString('N'))
[IO.Directory]::CreateDirectory($fixtureDirectory) > $null
$databasePath = Join-Path $fixtureDirectory 'isolated.fdb'
$connectionString = "Database=$databasePath;User=SYSDBA;Password=isolated-test-only;Charset=UTF8;ServerType=1;ClientLibrary=$ClientLibrary;Pooling=false"
[FirebirdSql.Data.FirebirdClient.FbConnection]::CreateDatabase($connectionString)
$connection = [FirebirdSql.Data.FirebirdClient.FbConnection]::new($connectionString)
function Query([string]$sql, [switch]$Scalar) {
    $command = $connection.CreateCommand(); $command.CommandText = $sql
    if ($script:migrationTransaction) { $command.Transaction = $script:migrationTransaction }
    try { if ($Scalar) { return $command.ExecuteScalar() }; $command.ExecuteNonQuery() > $null }
    finally { $command.Dispose() }
}
function Migrate {
    $sql = [IO.File]::ReadAllText((Join-Path $root 'docs/sql/scripts/add-studio-rascunhos.sql'))
    $script:migrationTransaction = $connection.BeginTransaction()
    try {
    foreach ($part in ($sql -split '-- @statement' | Select-Object -Skip 1)) {
        $statement = $part.Trim().TrimEnd(';')
        if ($statement -match '^CREATE (TABLE|INDEX) (\w+)') {
            $kind = $Matches[1]; $name = $Matches[2]
            $table = if ($kind -eq 'TABLE') { 'RDB$RELATIONS' } else { 'RDB$INDICES' }
            $field = if ($kind -eq 'TABLE') { 'RDB$RELATION_NAME' } else { 'RDB$INDEX_NAME' }
            if ((Query "SELECT COUNT(*) FROM $table WHERE $field='$name'" -Scalar) -gt 0) { continue }
        }
        Query $statement
    }
    $script:migrationTransaction.Commit()
    } finally { $script:migrationTransaction.Dispose(); $script:migrationTransaction = $null }
    Query 'INSERT INTO STUDIOMODELOESTADO(CODMODELO,VERSAO) SELECT M.CODMODELO,0 FROM MODELOMODOTEXTO M WHERE NOT EXISTS(SELECT 1 FROM STUDIOMODELOESTADO S WHERE S.CODMODELO=M.CODMODELO)'
}
try {
    $connection.Open()
    Query 'CREATE TABLE USUARIO(CODUSUARIO INTEGER NOT NULL PRIMARY KEY)'
    Query 'CREATE TABLE MODELOMODOTEXTO(CODMODELO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,NOME VARCHAR(120) CHARACTER SET UTF8,CODUSUARIO INTEGER NOT NULL,DTHRULTMODIFICACAO TIMESTAMP)'
    Query 'CREATE TABLE SECAOMODOTEXTO(CODSECAO INTEGER NOT NULL PRIMARY KEY,CODMODELO INTEGER NOT NULL,NOME VARCHAR(120),ORDEM INTEGER,POSICAO_X INTEGER,POSICAO_Y INTEGER,LARGURA INTEGER,ALTURA INTEGER)'
    Query 'CREATE TABLE SECAO_VARIAVEL(CODSECAO INTEGER NOT NULL,CODVARIAVEL INTEGER NOT NULL,ORDEM INTEGER,EXIBIR_GRAFICO BOOLEAN)'
    Query 'INSERT INTO USUARIO VALUES(1)'
    Query "INSERT INTO MODELOMODOTEXTO(CODMODELO,NOME,CODUSUARIO) VALUES(1,'Existing model',1)"
    Migrate
    Query "UPDATE MODELOMODOTEXTO SET NOME='Legacy update' WHERE CODMODELO=1"
    Query "INSERT INTO SECAOMODOTEXTO VALUES(1,1,'Section',1,0,0,6,4)"
    Query 'INSERT INTO SECAO_VARIAVEL VALUES(1,10,1,FALSE)'
    $version = Query 'SELECT VERSAO FROM STUDIOMODELOESTADO WHERE CODMODELO=1' -Scalar
    if ($version -lt 3) { throw 'Legacy changes did not invalidate publication versions.' }
    Migrate
    if ((Query 'SELECT VERSAO FROM STUDIOMODELOESTADO WHERE CODMODELO=1' -Scalar) -ne $version) { throw 'Repeating migration reset model version.' }
    $draftId = [Guid]::NewGuid().ToString(); $publicationId = [Guid]::NewGuid().ToString()
    Query "INSERT INTO STUDIORASCUNHO(CODRASCUNHO,CODUSUARIO,NOME,DOCUMENTO,DTHRCRIACAO,DTHRULTMODIFICACAO) VALUES('$draftId',1,'Draft','{}',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)"
    $unicode = ConvertFrom-Json '"\u00c1trio esquerdo | fra\u00e7\u00e3o | m\u00b2 | \u2264"'
    Query "UPDATE STUDIORASCUNHO SET DOCUMENTO='$unicode' WHERE CODRASCUNHO='$draftId'"
    if ((Query "SELECT DOCUMENTO FROM STUDIORASCUNHO WHERE CODRASCUNHO='$draftId'" -Scalar) -cne $unicode) { throw 'UTF-8 BLOB round trip failed.' }
    # Simulate a partially installed NEW schema only in this isolated fixture.
    if ((Query 'SELECT COUNT(*) FROM STUDIOPUBLICACAO' -Scalar) -ne 0) { throw 'Fixture table is not empty; refusing partial-schema test.' }
    Query 'DROP TABLE STUDIOPUBLICACAO'
    Migrate
    if ((Query "SELECT DOCUMENTO FROM STUDIORASCUNHO WHERE CODRASCUNHO='$draftId'" -Scalar) -cne $unicode) { throw 'Partial-schema repair changed existing draft data.' }
    $commandId = [Guid]::NewGuid().ToString()
    Query "INSERT INTO STUDIOREVISAO(CODRASCUNHO,NUMERO,CODCOMANDO,SHA256,TIPO,ORIGEM,GRUPOOPERACAO,DESCRICAO,DOCUMENTO,DETALHES,DTHRCRIACAO) VALUES('$draftId',0,'$commandId','HASH','create','manual','operation','Created','{}','{}',CURRENT_TIMESTAMP)"
    $script:migrationTransaction = $connection.BeginTransaction()
    $rejected = $false
    try {
        Query "UPDATE STUDIORASCUNHO SET REVISAO=1 WHERE CODRASCUNHO='$draftId'"
        Query "INSERT INTO STUDIOREVISAO(CODRASCUNHO,NUMERO,CODCOMANDO,SHA256,TIPO,ORIGEM,GRUPOOPERACAO,DESCRICAO,DOCUMENTO,DETALHES,DTHRCRIACAO) VALUES('$draftId',1,'$commandId','HASH','rename','manual','operation','Rename','{}','{}',CURRENT_TIMESTAMP)"
    } catch { $rejected = $true }
    finally { $script:migrationTransaction.Rollback(); $script:migrationTransaction.Dispose(); $script:migrationTransaction = $null }
    if (!$rejected -or (Query "SELECT REVISAO FROM STUDIORASCUNHO WHERE CODRASCUNHO='$draftId'" -Scalar) -ne 0 -or
        (Query "SELECT COUNT(*) FROM STUDIOREVISAO WHERE CODRASCUNHO='$draftId'" -Scalar) -ne 1) { throw 'Idempotency/transaction rollback failed.' }
    if ((Query "SELECT COUNT(*) FROM STUDIORASCUNHO WHERE CODRASCUNHO='$draftId' AND CODUSUARIO=2" -Scalar) -ne 0) { throw 'Owner isolation predicate failed.' }
    Query "INSERT INTO STUDIOPUBLICACAO(CODPUBLICACAO,CODUSUARIO,CODRASCUNHO,REVISAO,CODMODELO,NOME,ESTADO,DOCUMENTO,HASHCATALOGO,DTHRCRIACAO) VALUES('$publicationId',1,'$draftId',0,1,'Published','publicada','{}','HASH',CURRENT_TIMESTAMP)"
    Query "DELETE FROM STUDIOREVISAO WHERE CODRASCUNHO='$draftId'"
    Query "DELETE FROM STUDIORASCUNHO WHERE CODRASCUNHO='$draftId'"
    if ((Query "SELECT COUNT(*) FROM STUDIOPUBLICACAO WHERE CODPUBLICACAO='$publicationId' AND CODRASCUNHO IS NULL" -Scalar) -ne 1) { throw 'Deleting draft lost published history.' }
    Query 'DELETE FROM SECAO_VARIAVEL WHERE CODSECAO=1'; Query 'DELETE FROM SECAOMODOTEXTO WHERE CODSECAO=1'; Query 'DELETE FROM MODELOMODOTEXTO WHERE CODMODELO=1'
    if ((Query "SELECT COUNT(*) FROM STUDIOPUBLICACAO WHERE CODPUBLICACAO='$publicationId' AND CODMODELO IS NULL" -Scalar) -ne 1) { throw 'Deleting model lost published history.' }
    Write-Output 'PASS: clean/repeated/partial migration, UTF-8, idempotency constraint, rollback, owner predicate, legacy version triggers and published-history preservation.'
    Write-Output "Isolated fixture retained at: $databasePath"
} finally { $connection.Dispose() }
