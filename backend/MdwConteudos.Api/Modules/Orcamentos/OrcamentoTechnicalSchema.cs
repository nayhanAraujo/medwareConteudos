using Dapper;
using MdwConteudos.Api.Infrastructure;

namespace MdwConteudos.Api.Modules.Orcamentos;

public static class OrcamentoTechnicalSchema
{
    public static async Task Migrate(IFirebirdConnectionFactory db, CancellationToken ct)
    {
        await using var c = await db.OpenConnectionAsync(ct);
        foreach (var (table, definition) in new[] {
            ("ORCAMENTOREGRAVERSAO", "CODORCAMENTOREGRAVERSAO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, DOCUMENTO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL, MOTIVO VARCHAR(1000) CHARACTER SET UTF8 NOT NULL, CODUSUARIO INTEGER NOT NULL, DTHRCRIACAO TIMESTAMP NOT NULL, CONSTRAINT PK_ORCAMENTOREGRAVERSAO PRIMARY KEY(CODORCAMENTOREGRAVERSAO)"),
            ("ORCAMENTOREGRACONFIG", "CODORCAMENTOREGRACONFIG INTEGER NOT NULL, CODORCAMENTOREGRAVERSAO BIGINT NOT NULL, CONSTRAINT PK_ORCAMENTOREGRACONFIG PRIMARY KEY(CODORCAMENTOREGRACONFIG), CONSTRAINT FK_ORCREGRACONFIG_VERSAO FOREIGN KEY(CODORCAMENTOREGRAVERSAO) REFERENCES ORCAMENTOREGRAVERSAO(CODORCAMENTOREGRAVERSAO)") })
            if (await c.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME=@table", new { table }) == 0)
                await c.ExecuteAsync(new CommandDefinition($"CREATE TABLE {table}({definition})", cancellationToken: ct));
        if (await c.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM ORCAMENTOREGRAVERSAO") == 0)
            await c.ExecuteAsync(new CommandDefinition("INSERT INTO ORCAMENTOREGRAVERSAO(DOCUMENTO,MOTIVO,CODUSUARIO,DTHRCRIACAO) VALUES(@json,'Catálogo inicial; exemplos de regras inativos para revisão da gestão',0,@now)", new { json = QuoteTextBlob.Json(QuoteTechnicalCatalog.Initial), now = DateTime.UtcNow }, cancellationToken: ct));
        if (await c.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM ORCAMENTOREGRACONFIG WHERE CODORCAMENTOREGRACONFIG=1") == 0)
            await c.ExecuteAsync("INSERT INTO ORCAMENTOREGRACONFIG(CODORCAMENTOREGRACONFIG,CODORCAMENTOREGRAVERSAO) SELECT 1,MAX(CODORCAMENTOREGRAVERSAO) FROM ORCAMENTOREGRAVERSAO");
    }
}
