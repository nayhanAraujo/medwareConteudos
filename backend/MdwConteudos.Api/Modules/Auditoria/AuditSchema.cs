using Dapper;
using FirebirdSql.Data.FirebirdClient;
using MdwConteudos.Api.Infrastructure;

namespace MdwConteudos.Api.Modules.Auditoria;

public static class AuditSchema
{
    private const string Version = "MDW_AUDIT_1";
    public static async Task MigrateAsync(IFirebirdConnectionFactory db, CancellationToken ct = default)
    {
        await using var conn = await db.OpenConnectionAsync(ct);
        if (!await Exists(conn, "RDB$RELATIONS", "RDB$RELATION_NAME", "AUDITORIA_EVENTO"))
            await conn.ExecuteAsync(new CommandDefinition("""
                CREATE TABLE AUDITORIA_EVENTO (
                  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  OCCURRED_UTC TIMESTAMP NOT NULL, MODULE VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
                  ACTION VARCHAR(40) CHARACTER SET UTF8 NOT NULL, RESULT VARCHAR(20) CHARACTER SET UTF8 NOT NULL,
                  ENTITY_TYPE VARCHAR(63) CHARACTER SET ASCII, ENTITY_ID VARCHAR(128) CHARACTER SET UTF8,
                  ENTITY_NAME VARCHAR(255) CHARACTER SET UTF8, SUMMARY VARCHAR(500) CHARACTER SET UTF8 NOT NULL,
                  ACTOR_ID INTEGER, ACTOR_NAME VARCHAR(255) CHARACTER SET UTF8,
                  ACTOR_KIND VARCHAR(20) CHARACTER SET UTF8 NOT NULL, ORIGIN VARCHAR(20) CHARACTER SET UTF8 NOT NULL,
                  CORRELATION_ID VARCHAR(128) CHARACTER SET UTF8, OPERATION_ID VARCHAR(64) CHARACTER SET UTF8,
                  REQUEST_METHOD VARCHAR(10) CHARACTER SET UTF8, REQUEST_PATH VARCHAR(255) CHARACTER SET UTF8,
                  IP_ADDRESS VARCHAR(64) CHARACTER SET UTF8, REASON_CODE VARCHAR(40) CHARACTER SET UTF8
                )
                """, cancellationToken: ct));
        if (!await Exists(conn, "RDB$RELATIONS", "RDB$RELATION_NAME", "AUDITORIA_ALTERACAO"))
            await conn.ExecuteAsync(new CommandDefinition("""
                CREATE TABLE AUDITORIA_ALTERACAO (
                  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  EVENT_ID BIGINT NOT NULL REFERENCES AUDITORIA_EVENTO(ID),
                  FIELD_NAME VARCHAR(100) CHARACTER SET UTF8 NOT NULL,
                  VALUE_TYPE VARCHAR(12) CHARACTER SET ASCII NOT NULL,
                  BEFORE_VALUE BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
                  AFTER_VALUE BLOB SUB_TYPE TEXT CHARACTER SET UTF8
                )
                """, cancellationToken: ct));
        var indexes = new Dictionary<string, string>
        {
            ["IX_AUD_DATA"] = "AUDITORIA_EVENTO (OCCURRED_UTC, ID)",
            ["IX_AUD_AUTOR"] = "AUDITORIA_EVENTO (ACTOR_ID, OCCURRED_UTC)",
            ["IX_AUD_MODULO"] = "AUDITORIA_EVENTO (MODULE, ACTION, OCCURRED_UTC)",
            ["IX_AUD_ENTIDADE"] = "AUDITORIA_EVENTO (ENTITY_TYPE, ENTITY_ID)",
            ["IX_AUD_CORRELACAO"] = "AUDITORIA_EVENTO (CORRELATION_ID)",
            ["IX_AUD_DIFERENCAS"] = "AUDITORIA_ALTERACAO (EVENT_ID)"
        };
        foreach (var index in indexes)
            if (!await Exists(conn, "RDB$INDICES", "RDB$INDEX_NAME", index.Key))
                await conn.ExecuteAsync(new CommandDefinition($"CREATE {(index.Key == "IX_AUD_DATA" ? "DESCENDING " : "")}INDEX {index.Key} ON {index.Value}", cancellationToken: ct));

        // This procedure runs in the caller's transaction. An insert failure aborts the business write.
        await conn.ExecuteAsync(new CommandDefinition("""
            CREATE OR ALTER PROCEDURE AUDIT_APPEND (
              P_MODULE VARCHAR(40) CHARACTER SET UTF8, P_ACTION VARCHAR(40) CHARACTER SET UTF8,
              P_TYPE VARCHAR(63) CHARACTER SET UTF8, P_ID VARCHAR(255) CHARACTER SET UTF8,
              P_NAME VARCHAR(255) CHARACTER SET UTF8)
            RETURNS (EVENT_ID BIGINT)
            AS /* MDW_AUDIT_1 */ BEGIN
              INSERT INTO AUDITORIA_EVENTO (OCCURRED_UTC,MODULE,ACTION,RESULT,ENTITY_TYPE,ENTITY_ID,ENTITY_NAME,SUMMARY,
                ACTOR_ID,ACTOR_NAME,ACTOR_KIND,ORIGIN,CORRELATION_ID,OPERATION_ID,REQUEST_METHOD,REQUEST_PATH,IP_ADDRESS)
              VALUES (CAST(CURRENT_TIMESTAMP AT TIME ZONE 'UTC' AS TIMESTAMP), :P_MODULE,:P_ACTION,'sucesso',:P_TYPE,:P_ID,:P_NAME,
                :P_ACTION || ' ' || :P_TYPE,
                CAST(RDB$GET_CONTEXT('USER_SESSION','AUD_ACTOR_ID') AS INTEGER),
                RDB$GET_CONTEXT('USER_SESSION','AUD_ACTOR_NAME'),
                COALESCE(RDB$GET_CONTEXT('USER_SESSION','AUD_ACTOR_KIND'),'sistema'),
                COALESCE(RDB$GET_CONTEXT('USER_SESSION','AUD_ORIGIN'),'sistema'),
                RDB$GET_CONTEXT('USER_SESSION','AUD_CORRELATION'),RDB$GET_CONTEXT('USER_SESSION','AUD_OPERATION'),
                RDB$GET_CONTEXT('USER_SESSION','AUD_METHOD'),RDB$GET_CONTEXT('USER_SESSION','AUD_PATH'),
                RDB$GET_CONTEXT('USER_SESSION','AUD_IP')) RETURNING ID INTO :EVENT_ID;
            END
            """, cancellationToken: ct));
        foreach (var entity in AuditEntities.All) await InstallTriggerAsync(conn, entity, ct);
    }

    private static async Task<bool> Exists(FbConnection conn, string table, string field, string name) =>
        await conn.ExecuteScalarAsync<int>($"SELECT COUNT(*) FROM {table} WHERE {field}=@name", new { name }) > 0;

    public static async Task ValidateAsync(IFirebirdConnectionFactory db, CancellationToken ct = default)
    {
        await using var conn = await db.OpenConnectionAsync(ct);
        static InvalidOperationException Missing() => new("Schema de auditoria ausente ou desatualizado. Execute --migrate-database antes de iniciar a API.");
        if (!await Exists(conn, "RDB$RELATIONS", "RDB$RELATION_NAME", "AUDITORIA_EVENTO") ||
            !await Exists(conn, "RDB$RELATIONS", "RDB$RELATION_NAME", "AUDITORIA_ALTERACAO")) throw Missing();
        var procedure = await conn.QuerySingleOrDefaultAsync<string>(new CommandDefinition(
            "SELECT RDB$PROCEDURE_SOURCE FROM RDB$PROCEDURES WHERE RDB$PROCEDURE_NAME='AUDIT_APPEND' AND COALESCE(RDB$VALID_BLR,1)=1", cancellationToken: ct));
        if (procedure?.Contains(Version, StringComparison.Ordinal) != true) throw Missing();
        foreach (var entity in AuditEntities.All)
        {
            if (!await Exists(conn, "RDB$RELATIONS", "RDB$RELATION_NAME", entity.Table)) continue;
            var source = await conn.QuerySingleOrDefaultAsync<string>(new CommandDefinition(
                "SELECT RDB$TRIGGER_SOURCE FROM RDB$TRIGGERS WHERE RDB$TRIGGER_NAME=@name AND RDB$TRIGGER_INACTIVE=0 AND COALESCE(RDB$VALID_BLR,1)=1", new { name = "AUD_" + entity.Table }, cancellationToken: ct));
            if (source?.Contains(Version, StringComparison.Ordinal) != true) throw Missing();
        }
    }

    public static async Task<IReadOnlyList<(string Table, bool Present, bool Installed)>> CoverageAsync(IFirebirdConnectionFactory db, CancellationToken ct = default)
    {
        await using var conn = await db.OpenConnectionAsync(ct);
        var result = new List<(string, bool, bool)>();
        foreach (var e in AuditEntities.All)
            result.Add((e.Table, await Exists(conn,"RDB$RELATIONS","RDB$RELATION_NAME",e.Table), await Exists(conn,"RDB$TRIGGERS","RDB$TRIGGER_NAME","AUD_"+e.Table)));
        return result;
    }

    private sealed record Column(string Name, short Type);
    private static async Task InstallTriggerAsync(FbConnection conn, AuditEntity entity, CancellationToken ct)
    {
        var columns = (await conn.QueryAsync<Column>(new CommandDefinition("""
            SELECT TRIM(r.RDB$FIELD_NAME) AS Name, f.RDB$FIELD_TYPE AS Type
            FROM RDB$RELATION_FIELDS r JOIN RDB$FIELDS f ON f.RDB$FIELD_NAME=r.RDB$FIELD_SOURCE
            WHERE r.RDB$RELATION_NAME=@table
            """, new { table = entity.Table }, cancellationToken: ct))).ToDictionary(c => c.Name, StringComparer.Ordinal);
        // Variant/optional tables are only instrumented if the declared identifiers exist.
        if (columns.Count == 0) return;
        if (entity.Keys.Any(k => !columns.ContainsKey(k)))
            throw new InvalidOperationException($"Chave de auditoria incompatível com {entity.Table}. Revise a migração antes do deploy.");
        var fields = entity.Fields.Where(f => columns.TryGetValue(f, out var c) && c.Type != 261).ToArray();
        var binaries = (entity.BinaryFields ?? []).Where(columns.ContainsKey).ToArray();
        string Value(string side, string field) => $"CAST({side}.{field} AS VARCHAR(1024) CHARACTER SET UTF8)";
        string Hash(string side, string field) => $"LOWER(HEX_ENCODE(CRYPT_HASH({side}.{field} USING SHA256)))";
        string BinaryChanged(string field) => $"CASE WHEN OLD.{field} IS NOT DISTINCT FROM NEW.{field} THEN FALSE ELSE ({Hash("OLD", field)} IS DISTINCT FROM {Hash("NEW", field)}) END";
        var differences = fields.Select(f => $"OLD.{f} IS DISTINCT FROM NEW.{f}")
            .Concat(binaries.Select(BinaryChanged)).ToList();
        var password = entity.Table == "USUARIO" && columns.ContainsKey("SENHA");
        var changed = differences.Count == 0 ? "FALSE" : string.Join(" OR ", differences);
        var body = new System.Text.StringBuilder();
        body.AppendLine($"CREATE OR ALTER TRIGGER AUD_{entity.Table} FOR {entity.Table} ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 100 AS");
        body.AppendLine($"DECLARE V_ID BIGINT; DECLARE V_ACTION VARCHAR(40); DECLARE V_ENTITY VARCHAR(255) CHARACTER SET UTF8; DECLARE V_NAME VARCHAR(255) CHARACTER SET UTF8; /* {Version} */ BEGIN");
        body.AppendLine("IF (RDB$GET_CONTEXT('USER_SESSION','AUD_ENABLED') IS DISTINCT FROM '1') THEN EXIT;");
        body.AppendLine("IF (RDB$GET_CONTEXT('USER_TRANSACTION','AUD_SUPPRESS') = '1') THEN EXIT;");
        body.AppendLine($"IF (UPDATING AND NOT ({changed}){(password ? " AND OLD.SENHA IS NOT DISTINCT FROM NEW.SENHA" : "")}) THEN EXIT;");
        string Identifier(string side) => string.Join(" || ':' || ", entity.Keys.Select(k => $"COALESCE(CAST({side}.{k} AS VARCHAR(100) CHARACTER SET UTF8),'~')"));
        string Name(string side) => entity.Name is not null && columns.ContainsKey(entity.Name)
            ? $"SUBSTRING(CAST({side}.{entity.Name} AS VARCHAR(1024) CHARACTER SET UTF8) FROM 1 FOR 255)" : "NULL";
        body.AppendLine($"IF (DELETING) THEN BEGIN V_ENTITY={Identifier("OLD")}; V_NAME={Name("OLD")}; V_ACTION='{(entity.File ? "remover_anexo" : entity.Link ? "desvincular" : "excluir")}'; END");
        body.AppendLine($"ELSE BEGIN V_ENTITY={Identifier("NEW")}; V_NAME={Name("NEW")}; IF (INSERTING) THEN V_ACTION='{(entity.File ? "upload" : entity.Link ? "vincular" : "criar")}'; ELSE V_ACTION='editar'; END");
        foreach (var status in new[] { "STATUS", "ATIVO", "PUBLICADO", "APROVADO" }.Where(columns.ContainsKey))
        {
            var active = $"UPPER(TRIM(CAST(NEW.{status} AS VARCHAR(16)))) IN ('-1','1','T','TRUE','S','SIM')";
            body.AppendLine($"IF (UPDATING AND OLD.{status} IS DISTINCT FROM NEW.{status}) THEN BEGIN IF ({active}) THEN V_ACTION='{(status == "APROVADO" ? "aprovar" : "ativar")}'; ELSE V_ACTION='{(status == "APROVADO" ? "reprovar" : "inativar")}'; END");
        }
        body.AppendLine($"IF (INSERTING AND RDB$GET_CONTEXT('USER_SESSION','AUD_IMPORT')='1' AND V_ACTION='criar') THEN V_ACTION='importar';");
        if (password) body.AppendLine($"IF (UPDATING AND NOT ({changed}) AND OLD.SENHA IS DISTINCT FROM NEW.SENHA) THEN V_ACTION=COALESCE(RDB$GET_CONTEXT('USER_SESSION','AUD_PASSWORD_ACTION'),'alterar_senha');");
        if (columns.ContainsKey("STATUS_VALIDACAO"))
            body.AppendLine("IF (NOT DELETING AND (INSERTING OR OLD.STATUS_VALIDACAO IS DISTINCT FROM NEW.STATUS_VALIDACAO)) THEN BEGIN IF (NEW.STATUS_VALIDACAO='A') THEN V_ACTION='aprovar'; ELSE IF (NEW.STATUS_VALIDACAO='R') THEN V_ACTION='reprovar'; END");
        var module = password ? $"IIF(:V_ACTION IN ('alterar_senha','redefinir_senha'),'autenticacao','{entity.Module}')" : $"'{entity.Module}'";
        body.AppendLine($"EXECUTE PROCEDURE AUDIT_APPEND({module},:V_ACTION,'{entity.Table}',:V_ENTITY,:V_NAME) RETURNING_VALUES :V_ID;");
        foreach (var field in fields)
        {
            var type = columns[field].Type switch { 7 or 8 or 10 or 16 or 24 or 25 or 26 or 27 => "number", 23 => "boolean", _ => "string" };
            body.AppendLine($"IF ((INSERTING AND NEW.{field} IS NOT NULL) OR (DELETING AND OLD.{field} IS NOT NULL) OR (UPDATING AND OLD.{field} IS DISTINCT FROM NEW.{field})) THEN BEGIN");
            body.AppendLine($"INSERT INTO AUDITORIA_ALTERACAO(EVENT_ID,FIELD_NAME,VALUE_TYPE,BEFORE_VALUE,AFTER_VALUE) VALUES (:V_ID,'{field.ToLowerInvariant()}','{type}',IIF(INSERTING,NULL,{Value("OLD",field)}),IIF(DELETING,NULL,{Value("NEW",field)})); END");
        }
        foreach (var field in binaries)
        {
            body.AppendLine($"IF (INSERTING OR DELETING OR ({BinaryChanged(field)})) THEN BEGIN");
            body.AppendLine($"INSERT INTO AUDITORIA_ALTERACAO(EVENT_ID,FIELD_NAME,VALUE_TYPE,BEFORE_VALUE,AFTER_VALUE) VALUES (:V_ID,'{field.ToLowerInvariant()}_sha256','string',IIF(INSERTING,NULL,{Hash("OLD",field)}),IIF(DELETING,NULL,{Hash("NEW",field)}));");
            body.AppendLine($"INSERT INTO AUDITORIA_ALTERACAO(EVENT_ID,FIELD_NAME,VALUE_TYPE,BEFORE_VALUE,AFTER_VALUE) VALUES (:V_ID,'{field.ToLowerInvariant()}_bytes','number',IIF(INSERTING,NULL,CAST(OCTET_LENGTH(OLD.{field}) AS VARCHAR(32))),IIF(DELETING,NULL,CAST(OCTET_LENGTH(NEW.{field}) AS VARCHAR(32)))); END");
        }
        // Password values never enter differences, even in hashed form.
        if (password) body.AppendLine($"IF (UPDATING AND ({changed}) AND OLD.SENHA IS DISTINCT FROM NEW.SENHA) THEN EXECUTE PROCEDURE AUDIT_APPEND('autenticacao',COALESCE(RDB$GET_CONTEXT('USER_SESSION','AUD_PASSWORD_ACTION'),'alterar_senha'),'USUARIO',:V_ENTITY,:V_NAME) RETURNING_VALUES :V_ID;");
        body.AppendLine("END");
        await conn.ExecuteAsync(new CommandDefinition(body.ToString(), cancellationToken: ct));
    }
}
