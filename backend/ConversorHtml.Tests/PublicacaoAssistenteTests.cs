    [FirebirdPublicationFact]
    public async Task BatchDeletionIsAtomicAndQueuesDestinationDeletion()
    {
        await Seed();
        await service.ProcessNext(default);
        await using var source = new FbConnection(sourceCs);
        await source.OpenAsync();
        foreach (var sql in new[] {
            "CREATE TABLE SCRIPTARQUIVOS (CODSCRIPTLAUDO INTEGER REFERENCES SCRIPTLAUDO(CODSCRIPTLAUDO))",
            "CREATE TABLE SCRIPTAPROVACAOTOKEN (CODSCRIPTLAUDO INTEGER REFERENCES SCRIPTLAUDO(CODSCRIPTLAUDO))",
            "CREATE TABLE SCRIPTLAUDO_VARIAVEL (CODSCRIPTLAUDO INTEGER REFERENCES SCRIPTLAUDO(CODSCRIPTLAUDO))",
            "CREATE TABLE SCRIPTVERSAOARQUIVOS (CODVERSAO INTEGER REFERENCES SCRIPTVERSOES(CODVERSAO))",
            "CREATE TABLE SCRIPTVERSAOHISTORICO (CODVERSAO_ORIGEM INTEGER REFERENCES SCRIPTVERSOES(CODVERSAO), CODVERSAO_DESTINO INTEGER REFERENCES SCRIPTVERSOES(CODVERSAO))",
            "INSERT INTO SCRIPTVERSOES (CODVERSAO,CODSCRIPTLAUDO,ATIVO) VALUES (10,1,'F')",
            "INSERT INTO SCRIPTVERSAOARQUIVOS VALUES (10)",
            "INSERT INTO SCRIPTVERSAOHISTORICO VALUES (10,10)",
            "INSERT INTO SCRIPTARQUIVOS VALUES (1)",
            "INSERT INTO SCRIPTAPROVACAOTOKEN VALUES (1)",
            "INSERT INTO SCRIPTLAUDO_VARIAVEL VALUES (1)" })
            await source.ExecuteAsync(sql);
        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?> {
            ["Firebird:Database"] = new FbConnectionStringBuilder(sourceCs).Database,
            ["DataPaths:Root"] = Path.GetTempPath()
        }).Build();
        var scripts = new ScriptsService(config, NullLogger<ScriptsService>.Instance, new TestEnvironment(), new TargetFactory(targetCs));
        typeof(ScriptsService).GetField("_connectionString", BindingFlags.Instance | BindingFlags.NonPublic)!.SetValue(scripts, sourceCs);
        await Assert.ThrowsAsync<InvalidOperationException>(() => scripts.DeleteScriptsAsync([1,999]));
        Assert.Equal(1, await source.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM SCRIPTLAUDO"));
        Assert.Equal(1, await source.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM SCRIPTARQUIVOS"));
        await source.ExecuteAsync("CREATE TABLE DELETE_BLOCKER (SCRIPT_ID INTEGER REFERENCES SCRIPTLAUDO(CODSCRIPTLAUDO))");
        await source.ExecuteAsync("INSERT INTO DELETE_BLOCKER VALUES (1)");
        await Assert.ThrowsAsync<FbException>(() => scripts.DeleteScriptsAsync([1]));
        Assert.Equal(1, await source.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM SCRIPTARQUIVOS"));
        Assert.Equal(1, await source.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM SCRIPTVERSAOHISTORICO"));
        await source.ExecuteAsync("DROP TABLE DELETE_BLOCKER");
        Assert.Equal(1, await scripts.DeleteScriptsAsync([1,1]));
        foreach (var table in new[] { "SCRIPTLAUDO", "SCRIPTVERSOES", "SCRIPTVERSAOARQUIVOS", "SCRIPTVERSAOHISTORICO", "SCRIPTARQUIVOS", "SCRIPTAPROVACAOTOKEN", "SCRIPTLAUDO_VARIAVEL" })
            Assert.Equal(0, await source.ExecuteScalarAsync<int>($"SELECT COUNT(*) FROM {table}"));
        Assert.Equal("pendente", await source.ExecuteScalarAsync<string>("SELECT ESTADO FROM ASS_PUBLICACAO"));
        await service.ProcessNext(default);
        await using var target = new FbConnection(targetCs);
        Assert.Equal(0, await target.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM SCRIPTLAUDO"));
    }

