    private static async Task Migrate(FbConnection connection, string file)
    {
        var root = new DirectoryInfo(AppContext.BaseDirectory);
        while (root is not null && !Directory.Exists(Path.Combine(root.FullName, "backend", "sql"))) root = root.Parent;
        var path = root is not null ? Path.Combine(root.FullName, "backend", "sql", file)
            : Path.Combine(Environment.GetEnvironmentVariable("PUBLICACAO_TEST_REPO")!, "backend", "sql", file);
        var script = new FbScript(await File.ReadAllTextAsync(path));
        script.Parse();
        foreach (var statement in script.Results)
            if (!statement.Text.Trim().Equals("COMMIT", StringComparison.OrdinalIgnoreCase)) await connection.ExecuteAsync(statement.Text);
    }

