using System.Text.Json;
using Dapper;
using FirebirdSql.Data.FirebirdClient;
using MdwConteudos.Api.Infrastructure;
using MdwConteudos.Api.Modules.Cadastros;
using MdwConteudos.Api.Modules.Web;

namespace ConversorHtml.Tests;

public sealed class ModuloRelatorioIconeTests
{
    [FirebirdPublicationFact]
    public async Task MigrationCrudAndFilteredListPreserveImageAndLinks()
    {
        var cs = new FbConnectionStringBuilder {
            Database = Path.Combine(Path.GetTempPath(), $"modulo-icons-{Guid.NewGuid():N}.fdb"),
            ServerType = FbServerType.Embedded, ClientLibrary = Environment.GetEnvironmentVariable("PUBLICACAO_TEST_FBCLIENT"),
            UserID = "SYSDBA", Password = "masterkey", Charset = "UTF8", Pooling = false
        }.ToString();
        FbConnection.CreateDatabase(cs, overwrite: false);
        try
        {
            var factory = new Factory(cs);
            await using (var c = await factory.OpenConnectionAsync())
            {
                await c.ExecuteAsync("CREATE TABLE MODULORELATORIO (CODMODULO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,NOME VARCHAR(100),DESCRICAO VARCHAR(200),ATIVO INTEGER DEFAULT 1,DTHRCRIACAO TIMESTAMP,DTHRATUALIZACAO TIMESTAMP,USUARIOCRIACAO INTEGER,USUARIOATUALIZACAO INTEGER)");
                await c.ExecuteAsync("CREATE TABLE SISTEMA (CODSISTEMA INTEGER PRIMARY KEY,NOME VARCHAR(100))");
                await c.ExecuteAsync("CREATE TABLE SISTEMA_MODULO (CODSISTEMA INTEGER,CODMODULO INTEGER)");
                await c.ExecuteAsync("CREATE TABLE RELATORIOS (CODMODULO INTEGER,MODULO VARCHAR(100),DTHRCRIACAO TIMESTAMP)");
                await c.ExecuteAsync("INSERT INTO SISTEMA VALUES (1,'Sistema')");
            }
            await ModuloRelatorioIcone.MigrateAsync(factory);
            await ModuloRelatorioIcone.MigrateAsync(factory);
            using var stream = typeof(PacoteIcone).Assembly.GetManifestResourceStream("MdwConteudos.Api.Assets.Pacotes.consulta.png")!;
            using var buffer = new MemoryStream(); await stream.CopyToAsync(buffer);
            var icon = PacoteIcone.Prefix + Convert.ToBase64String(buffer.ToArray());
            var service = new RelatoriosWebService(factory);
            await service.CreateModuloAsync(new("Agenda", "Teste", [1], icon), 1, default);
            var list = JsonSerializer.SerializeToElement(await service.ListModulosAsync(1, default)).GetProperty("modulos");
            Assert.Equal(icon, list[0].GetProperty("iconeBase64").GetString());
            var id = list[0].GetProperty("codmodulo").GetInt32();
            await using (var c = await factory.OpenConnectionAsync())
                await c.ExecuteAsync("INSERT INTO RELATORIOS VALUES (@id,'Agenda',CURRENT_TIMESTAMP)", new { id });
            await service.UpdateModuloAsync("Agenda", new("Agenda", "Editado", [1], icon), 1, default);
            await ModuloRelatorioIcone.MigrateAsync(factory);
            var updated = JsonSerializer.SerializeToElement(await service.ListModulosAsync(null, default)).GetProperty("modulos")[0];
            Assert.Equal(icon, updated.GetProperty("iconeBase64").GetString());
            Assert.Equal(1, updated.GetProperty("total_relatorios").GetInt32());
            Assert.Single(updated.GetProperty("sistemas").EnumerateArray());
            await Assert.ThrowsAsync<InvalidOperationException>(() => service.UpdateModuloAsync("Agenda", new("Agenda", null, [1], "invalid"), 1, default));
            await service.UpdateModuloAsync("Agenda", new("Agenda", "Editado", null, null), 1, default);
            var removed = JsonSerializer.SerializeToElement(await service.ListModulosAsync(1, default)).GetProperty("modulos")[0];
            Assert.Equal(JsonValueKind.Null, removed.GetProperty("iconeBase64").ValueKind);
            Assert.Equal(1, removed.GetProperty("total_relatorios").GetInt32());
            Assert.Single(removed.GetProperty("sistemas").EnumerateArray());
        }
        finally { FbConnection.DropDatabase(cs); }
    }
    private sealed class Factory(string cs) : IFirebirdConnectionFactory
    {
        public async Task<FbConnection> OpenConnectionAsync(CancellationToken ct = default)
        {
            var c = new FbConnection(cs); await c.OpenAsync(ct); return c;
        }
    }
}
