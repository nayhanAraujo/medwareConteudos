    [FirebirdPublicationFact]
    public async Task MigrationRepeatsRealDiffsAreTypedAndNoopDoesNotWrite()
    {
        await using var conn = await factory.OpenConnectionAsync();
        await conn.ExecuteAsync("INSERT INTO NORMALIDADE(CODNORMALIDADE,CODVARIAVEL,VALORMIN,VALORMAX) VALUES (1,2,12.3400,44.5)");
        var reader = new AuditReader(factory, TimeProvider.System);
        var page = await reader.ListAsync(new() { Module = "referencias" });
        var item = Assert.Single(page.Data);
        Assert.Equal("1", item.ActorId?.ToString());
        Assert.EndsWith("Z", item.OccurredAtUtc);
        var detail = await reader.GetAsync(long.Parse(item.Id));
        Assert.Equal(12.3400m, Assert.Single(detail!.Changes.Where(c => c.Field == "valormin")).After);
        await conn.ExecuteAsync("UPDATE NORMALIDADE SET VALORMIN=VALORMIN WHERE CODNORMALIDADE=1");
        Assert.Equal(1, await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM AUDITORIA_EVENTO"));
        await conn.ExecuteAsync("UPDATE NORMALIDADE SET VALORMIN=NULL WHERE CODNORMALIDADE=1");
        detail = await reader.GetAsync(await conn.ExecuteScalarAsync<long>("SELECT MAX(ID) FROM AUDITORIA_EVENTO"));
        var change = Assert.Single(detail!.Changes);
        Assert.Equal(12.3400m, change.Before); Assert.Null(change.After);
    }

    [FirebirdPublicationFact]
    public async Task AuditFailureRollsBackBusinessInAutocommitAndExplicitTransaction()
    {
        await using var conn = await factory.OpenConnectionAsync();
        await conn.ExecuteAsync("CREATE EXCEPTION FAIL_AUDIT 'forced audit failure'");
        await conn.ExecuteAsync("CREATE TRIGGER FAIL_AUDIT_WRITE FOR AUDITORIA_EVENTO BEFORE INSERT AS BEGIN EXCEPTION FAIL_AUDIT; END");
        await Assert.ThrowsAsync<FbException>(() => conn.ExecuteAsync("INSERT INTO PACOTES(CODPACOTE,NOME) VALUES (1,'one')"));
        Assert.Equal(0, await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM PACOTES"));
        await using (var tx = await conn.BeginTransactionAsync())
        {
            await Assert.ThrowsAsync<FbException>(() => conn.ExecuteAsync("INSERT INTO PACOTES(CODPACOTE,NOME) VALUES (2,'two')", transaction: tx));
            await tx.RollbackAsync();
        }
        Assert.Equal(0, await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM PACOTES"));
        Assert.Equal(0, await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM AUDITORIA_EVENTO"));
    }

