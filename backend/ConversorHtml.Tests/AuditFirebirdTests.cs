    [FirebirdPublicationFact]
    public async Task SuppressionIsTransactionLocalAndRootDeleteDoesNotDuplicateChildRemoval()
    {
        await using var conn = await factory.OpenConnectionAsync();
        await conn.ExecuteAsync("INSERT INTO SCRIPTLAUDO(CODSCRIPTLAUDO,NOME) VALUES(37,'script')");
        await conn.ExecuteAsync("INSERT INTO SCRIPTLAUDOMRD(CODSCRIPTMRD,CODSCRIPTLAUDO,NOME_ARQUIVO) VALUES(1,37,'x.mrd')");
        var before = await conn.ExecuteScalarAsync<long>("SELECT MAX(ID) FROM AUDITORIA_EVENTO");
        await using (var tx = await conn.BeginTransactionAsync())
        {
            await AuditSession.SuppressAsync(conn, tx, true);
            await conn.ExecuteAsync("DELETE FROM SCRIPTLAUDOMRD WHERE CODSCRIPTLAUDO=37", transaction: tx);
            await AuditSession.SuppressAsync(conn, tx, false);
            await conn.ExecuteAsync("DELETE FROM SCRIPTLAUDO WHERE CODSCRIPTLAUDO=37", transaction: tx);
            await tx.CommitAsync();
        }
        Assert.Equal(1, await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM AUDITORIA_EVENTO WHERE ID>@before", new { before }));
        await conn.ExecuteAsync("INSERT INTO SCRIPTLAUDOMRD(CODSCRIPTMRD,NOME_ARQUIVO) VALUES(2,'y.mrd')");
        Assert.Equal(1, await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM AUDITORIA_EVENTO WHERE ENTITY_TYPE='SCRIPTLAUDOMRD' AND ENTITY_ID='2'"));
    }

