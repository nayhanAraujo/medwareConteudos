using Microsoft.AspNetCore.Hosting;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.FileProviders;

namespace ConversorHtml.Tests;

public sealed class PacoteIconeTests
{
    private static string Icon(string name = "cardiologia")
    {
        using var stream = typeof(PacoteIcone).Assembly.GetManifestResourceStream($"MdwConteudos.Api.Assets.Pacotes.{name}.png")!;
        using var buffer = new MemoryStream();
        stream.CopyTo(buffer);
        return PacoteIcone.Prefix + Convert.ToBase64String(buffer.ToArray());
    }

    [Fact]
    public void ValidatesGalleryAndRejectsInvalidImages()
    {
        foreach (var name in new[] { "cardiologia", "ultrassonografia", "vascular", "oftalmologia", "pediatria", "nutricao", "consulta" })
            Assert.Equal(Icon(name), PacoteIcone.Validate(Icon(name)));
        Assert.Null(PacoteIcone.Validate(null));
        Assert.Null(PacoteIcone.Validate(""));
        foreach (var value in new[] { "data:image/jpeg;base64,AAAA", PacoteIcone.Prefix + "!", PacoteIcone.Prefix + "AAAA", PacoteIcone.Prefix + new string('A', 1400000) })
            Assert.Throws<InvalidOperationException>(() => PacoteIcone.Validate(value));
        var invalid = Convert.FromBase64String(Icon()[PacoteIcone.Prefix.Length..]);
        invalid[0] = 0;
        Assert.Throws<InvalidOperationException>(() => PacoteIcone.Validate(PacoteIcone.Prefix + Convert.ToBase64String(invalid)));
    }

    [FirebirdPublicationFact]
    public async Task MigrationAndCrudPreserveIconsAndScriptAssociations()
    {
        var cs = new FbConnectionStringBuilder {
            Database = Path.Combine(Path.GetTempPath(), $"pacote-icons-{Guid.NewGuid():N}.fdb"),
            ServerType = FbServerType.Embedded, ClientLibrary = Environment.GetEnvironmentVariable("PUBLICACAO_TEST_FBCLIENT"),
            UserID = "SYSDBA", Password = "masterkey", Charset = "UTF8", Pooling = false
        }.ToString();
        FbConnection.CreateDatabase(cs, overwrite: false);
        try
        {
            var factory = new Factory(cs);
            await using (var c = await factory.OpenConnectionAsync())
            {
                await c.ExecuteAsync("CREATE TABLE PACOTES (CODPACOTE INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NOME VARCHAR(100), DESCRICAO VARCHAR(200), CODUSUARIO INTEGER, DTHRULTMODIFICACAO TIMESTAMP)");
                await c.ExecuteAsync("CREATE TABLE SCRIPTLAUDO (CODSCRIPTLAUDO INTEGER PRIMARY KEY, NOME VARCHAR(100), CODPACOTE INTEGER, DESCRICAO VARCHAR(200), LINGUAGEM VARCHAR(20), SISTEMA VARCHAR(40), APROVADO SMALLINT DEFAULT 0, DATA_VERIFICACAO TIMESTAMP, ATIVO SMALLINT DEFAULT 1, APROVADO_POR VARCHAR(100))");
                foreach (var name in new[] { "Cardiologia", "Ultrassonografia", "Angiologia e Cirurgia Vascular", "Oftalmologia", "Pediatria", "Nutrição", "Pacote de consulta" })
                    await c.ExecuteAsync("INSERT INTO PACOTES (NOME) VALUES (@name)", new { name });
                await c.ExecuteAsync("INSERT INTO SCRIPTLAUDO (CODSCRIPTLAUDO,NOME,CODPACOTE,LINGUAGEM,DATA_VERIFICACAO) VALUES (1,'Modelo',1,'HTML',CURRENT_TIMESTAMP)");
                await c.ExecuteAsync("INSERT INTO SCRIPTLAUDO (CODSCRIPTLAUDO,NOME,LINGUAGEM) VALUES (2,'Sem pacote','HTML')");
            }
            await PacoteIcone.MigrateAsync(factory);
            var service = new CadastrosService(factory);
            var initial = (await service.ListPacotes(default)).ToArray();
            Assert.Equal(7, initial.Length);
            Assert.All(initial, p => Assert.NotNull(p.IconeBase64));
            var heart = initial.Single(p => p.Nome == "Cardiologia");
            Assert.Equal(1, heart.QuantidadeScripts);
            var api = new ApiPublicaService(factory, Options.Create(new ApiPartnerOptions()), null!);
            var packages = Assert.IsType<OkObjectResult>(await api.GetPacotesAsync(default));
            var payload = JsonSerializer.SerializeToElement(packages.Value);
            Assert.Equal(7, payload.GetProperty("total").GetInt32());
            var package = payload.GetProperty("data").EnumerateArray().Single(p => p.GetProperty("codpacote").GetInt32() == heart.CodPacote);
            Assert.Equal($"/apiconteudos/v1/pacotes/{heart.CodPacote}/icone", package.GetProperty("icone_url").GetString());
            Assert.Equal(Icon(), package.GetProperty("icone_base64").GetString());
            var image = Assert.IsType<FileContentResult>(await api.GetPacoteIconeAsync(heart.CodPacote, default));
            Assert.Equal("image/png", image.ContentType);
            Assert.Equal(Convert.FromBase64String(Icon()[PacoteIcone.Prefix.Length..]), image.FileContents);
            Assert.NotNull(image.EntityTag);
            var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?> { ["DataPaths:Root"] = Path.GetTempPath() }).Build();
            var scripts = new ApiScriptOperations(factory, config, new TestEnvironment());
            var scriptList = await scripts.ListScriptsAsync(null, null, null, null, "HTML", false, default);
            Assert.Equal(package.GetProperty("icone_url").GetString(), scriptList.Single(s => (int)s["codscriptlaudo"]! == 1)["pacote_icone_url"]);
            Assert.Null(scriptList.Single(s => (int)s["codscriptlaudo"]! == 2)["pacote_icone_url"]);
            Assert.Equal(Icon(), scriptList.Single(s => (int)s["codscriptlaudo"]! == 1)["pacote_icone_base64"]);
            Assert.Null(scriptList.Single(s => (int)s["codscriptlaudo"]! == 2)["pacote_icone_base64"]);
            Assert.All(scriptList, s => Assert.False(s.ContainsKey("imagens")));
            var last = await scripts.GetUltimoVerificadoAsync(null, null, null, null, "HTML", false, default);
            Assert.Equal(package.GetProperty("icone_url").GetString(), last.Item!["pacote_icone_url"]);
            Assert.Equal(Icon(), last.Item["pacote_icone_base64"]);
            Assert.IsType<NotFoundObjectResult>(await api.GetPacoteIconeAsync(int.MaxValue, default));
            Assert.True(await service.UpdatePacote(heart.CodPacote, new(heart.Nome, "Editado", [1], Icon("consulta")), 1, default));
            var changed = Assert.IsType<FileContentResult>(await api.GetPacoteIconeAsync(heart.CodPacote, default));
            Assert.NotEqual(image.EntityTag, changed.EntityTag);
            await PacoteIcone.MigrateAsync(factory);
            var updated = (await service.ListPacotes(default)).Single(p => p.CodPacote == heart.CodPacote);
            Assert.Equal(Icon("consulta"), updated.IconeBase64);
            Assert.Equal(1, updated.QuantidadeScripts);
            Assert.True(await service.UpdatePacote(heart.CodPacote, new(heart.Nome, null, [1], null), 1, default));
            Assert.Null((await service.ListPacotes(default)).Single(p => p.CodPacote == heart.CodPacote).IconeBase64);
            Assert.IsType<NotFoundObjectResult>(await api.GetPacoteIconeAsync(heart.CodPacote, default));
            packages = Assert.IsType<OkObjectResult>(await api.GetPacotesAsync(default));
            payload = JsonSerializer.SerializeToElement(packages.Value);
            package = payload.GetProperty("data").EnumerateArray().Single(p => p.GetProperty("codpacote").GetInt32() == heart.CodPacote);
            Assert.Equal(JsonValueKind.Null, package.GetProperty("icone_url").ValueKind);
            Assert.Equal(JsonValueKind.Null, package.GetProperty("icone_base64").ValueKind);
            Assert.Null((await scripts.ListScriptsAsync(null, null, null, "1", "HTML", false, default)).Single()["pacote_icone_url"]);
            Assert.Null((await scripts.ListScriptsAsync(null, null, null, "1", "HTML", false, default)).Single()["pacote_icone_base64"]);
            await service.CreatePacote(new("Novo", null, [], Icon()), 1, default);
            var created = (await service.ListPacotes(default)).Single(p => p.Nome == "Novo");
            Assert.Equal(Icon(), created.IconeBase64);
            Assert.Equal(0, created.QuantidadeScripts);
            Assert.True(await service.DeletePacote(created.CodPacote, default));
        }
        finally { FbConnection.DropDatabase(cs); }
    }

    private sealed class Factory(string cs) : IFirebirdConnectionFactory
    {
        public async Task<FbConnection> OpenConnectionAsync(CancellationToken ct = default)
        {
            var connection = new FbConnection(cs);
            await connection.OpenAsync(ct);
            return connection;
        }
    }

    private sealed class TestEnvironment : IWebHostEnvironment
    {
        public string EnvironmentName { get; set; } = "Testing";
        public string ApplicationName { get; set; } = "MdwConteudos.Api";
        public string ContentRootPath { get; set; } = Path.GetTempPath();
        public IFileProvider ContentRootFileProvider { get; set; } = new NullFileProvider();
        public string WebRootPath { get; set; } = Path.GetTempPath();
        public IFileProvider WebRootFileProvider { get; set; } = new NullFileProvider();
    }
}
