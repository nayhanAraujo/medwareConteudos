        await conn.ExecuteAsync("UPDATE USUARIO SET STATUS=-1,EMAIL=NULL");
        Assert.True((await auth.LoginAsync("login", "old-password")).Success);
        await conn.ExecuteAsync("UPDATE USUARIO SET SENHA=NULL");
