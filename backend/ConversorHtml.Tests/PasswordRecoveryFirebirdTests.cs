using Dapper;
using FirebirdSql.Data.FirebirdClient;
using Microsoft.Extensions.Options;
using MdwConteudos.Api.Configuration;
using MdwConteudos.Api.Infrastructure;
using MdwConteudos.Api.Modules.Auth;
using MdwConteudos.Api.Modules.Users;

namespace ConversorHtml.Tests;

public sealed class PasswordRecoveryFirebirdTests : IAsyncLifetime
{
    private string cs = "";
    private Factory factory = null!;
    private FirebirdPasswordRecoveryStore store = null!;
    private static readonly DateTime Now = new(2026, 10, 21, 12, 0, 0, DateTimeKind.Utc);
    public async Task InitializeAsync()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("PUBLICACAO_TEST_FBCLIENT"))) return;
        cs = new FbConnectionStringBuilder {
            Database = Path.Combine(Path.GetTempPath(), $"recovery-test-{Guid.NewGuid():N}.fdb"),
            ServerType = FbServerType.Embedded, ClientLibrary = Environment.GetEnvironmentVariable("PUBLICACAO_TEST_FBCLIENT"),
            UserID = "SYSDBA", Password = "masterkey", Charset = "UTF8", Pooling = false
        }.ToString();
        FbConnection.CreateDatabase(cs);
        factory = new(cs); store = new(factory);
        await using var conn = await factory.OpenConnectionAsync();
        await conn.ExecuteAsync(@"CREATE TABLE USUARIO (CODUSUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            NOME VARCHAR(100), IDENTIFICACAO VARCHAR(100), UCASE_NOME VARCHAR(100), SENHA VARCHAR(64),
            PERFIL VARCHAR(20), STATUS INTEGER, DTHRULTMODIFICACAO TIMESTAMP)");
        await conn.ExecuteAsync("INSERT INTO USUARIO (NOME,IDENTIFICACAO,SENHA,PERFIL,STATUS) VALUES ('Name','login',@hash,'usuario',-1)", new { hash = PasswordHasher.Sha256Hex("old-password") });
        await PasswordRecoverySchema.MigrateAsync(factory);
        await PasswordRecoverySchema.MigrateAsync(factory);
        await conn.ExecuteAsync("UPDATE USUARIO SET EMAIL='name@example.test'");
    }

    public Task DisposeAsync() { if (cs != "") FbConnection.DropDatabase(cs); return Task.CompletedTask; }

    [FirebirdPublicationFact]
    public async Task ResetChangesLoginAndTokenCanOnlyBeUsedOnce()
    {
        Assert.NotNull(await store.IssueAsync("name@example.test", "hash", Now, default));
        Assert.True(await store.RedeemAsync("hash", PasswordHasher.Sha256Hex("new-password"), Now.AddMinutes(1), default));
        Assert.False(await store.RedeemAsync("hash", "other", Now.AddMinutes(1), default));
        var auth = new AuthService(factory, Options.Create(new WebAuthOptions { JwtSecret = new string('s', 48) }));
        Assert.True((await auth.LoginAsync("login", "new-password")).Success);
        Assert.False((await auth.LoginAsync("login", "old-password")).Success);
    }

    [FirebirdPublicationFact]
    public async Task ExpiredTamperedReplacedAndFailedDeliveryTokensCannotReset()
    {
        await store.IssueAsync("name@example.test", "first", Now, default);
        Assert.Null(await store.IssueAsync("name@example.test", "throttled", Now.AddSeconds(59), default));
        Assert.NotNull(await store.IssueAsync("name@example.test", "second", Now.AddMinutes(1), default));
        Assert.False(await store.RedeemAsync("first", "pw", Now.AddMinutes(2), default));
        Assert.False(await store.RedeemAsync("throttled", "pw", Now.AddMinutes(2), default));
        Assert.False(await store.RedeemAsync("tampered", "pw", Now.AddMinutes(2), default));
        Assert.False(await store.RedeemAsync("second", "pw", Now.AddMinutes(31), default));
        await store.IssueAsync("name@example.test", "failed", Now.AddMinutes(32), default);
        await store.InvalidateAsync("failed", Now.AddMinutes(32), default);
        Assert.False(await store.RedeemAsync("failed", "pw", Now.AddMinutes(33), default));
    }

    [FirebirdPublicationFact]
    public async Task InactiveMissingAndEmailLessAccountsCannotRecover()
    {
        Assert.Null(await store.IssueAsync("missing@example.test", "hash", Now, default));
        await using var conn = await factory.OpenConnectionAsync();
        await conn.ExecuteAsync("UPDATE USUARIO SET STATUS=0");
        Assert.Null(await store.IssueAsync("name@example.test", "hash", Now, default));
        await conn.ExecuteAsync("UPDATE USUARIO SET STATUS=-1");
        await store.IssueAsync("name@example.test", "hash", Now, default);
        await conn.ExecuteAsync("UPDATE USUARIO SET STATUS=0");
        Assert.False(await store.RedeemAsync("hash", "pw", Now.AddMinutes(1), default));
        await conn.ExecuteAsync("UPDATE USUARIO SET STATUS=-1,EMAIL=NULL");
        Assert.Null(await store.IssueAsync("name@example.test", "other", Now.AddMinutes(2), default));
    }

    [FirebirdPublicationFact]
    public async Task ConcurrentRedemptionsHaveExactlyOneWinner()
    {
        await store.IssueAsync("name@example.test", "hash", Now, default);
        var results = await Task.WhenAll(Enumerable.Range(0, 4).Select(_ => Task.Run(() => store.RedeemAsync("hash", "pw", Now.AddMinutes(1), default))));
        Assert.Equal(1, results.Count(x => x));
    }

    [FirebirdPublicationFact]
    public async Task AccountEditsPreserveOmittedEmailAndInvalidateLinks()
    {
        var users = new UsersService(factory);
        var user = Assert.Single(await users.ListAsync());
        var req = new UpdateUserRequest(user.Nome, user.Identificacao, null, null, user.Perfil, user.Status);
        Assert.True((await users.UpdateAsync(user.CodUsuario, req)).Ok);
        Assert.Equal("name@example.test", (await users.GetAsync(user.CodUsuario))!.Email);
        await store.IssueAsync("name@example.test", "password", Now, default);
        Assert.True((await users.UpdateAsync(user.CodUsuario, req with { Senha = "new-password", ConfirmarSenha = "new-password" })).Ok);
        Assert.False(await store.RedeemAsync("password", "pw", Now.AddMinutes(1), default));
        await store.IssueAsync("name@example.test", "email", Now.AddMinutes(2), default);
        Assert.True((await users.UpdateAsync(user.CodUsuario, req with { Email = " NEW@Example.Test " })).Ok);
        Assert.False(await store.RedeemAsync("email", "pw", Now.AddMinutes(3), default));
        Assert.Equal("new@example.test", (await users.GetAsync(user.CodUsuario))!.Email);
        Assert.True((await users.UpdateAsync(user.CodUsuario, req with { Email = "" })).Ok);
        Assert.Null((await users.GetAsync(user.CodUsuario))!.Email);
    }

    [FirebirdPublicationFact]
    public async Task EmailMustBeValidUniqueAndOptional()
    {
        var users = new UsersService(factory);
        var req = new CreateUserRequest("Other", "other", "secret", "secret", "usuario", -1, " NAME@example.test ");
        Assert.False((await users.CreateAsync(req)).Ok);
        Assert.False((await users.CreateAsync(req with { Email = "invalid" })).Ok);
        Assert.True((await users.CreateAsync(req with { Email = null })).Ok);
        await using var conn = await factory.OpenConnectionAsync();
        await Assert.ThrowsAsync<FbException>(() => conn.ExecuteAsync("UPDATE USUARIO SET EMAIL=' NAME@EXAMPLE.TEST ' WHERE IDENTIFICACAO='other'"));
    }

    private sealed class Factory(string connectionString) : IFirebirdConnectionFactory
    {
        public async Task<FbConnection> OpenConnectionAsync(CancellationToken ct = default)
        { var conn = new FbConnection(connectionString); await conn.OpenAsync(ct); return conn; }
    }
}
