CREATE TABLE SCRIPT_AVALIACAO (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 CODSCRIPTLAUDO INTEGER NOT NULL REFERENCES SCRIPTLAUDO(CODSCRIPTLAUDO),
 CODVERSAO INTEGER REFERENCES SCRIPTVERSOES(CODVERSAO),
 VERSAO_CHAVE INTEGER NOT NULL,
 IDENTIDADE CHAR(64) CHARACTER SET ASCII NOT NULL,
 ORIGEM VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
 CLIENTE_ID VARCHAR(80) CHARACTER SET UTF8 NOT NULL,
 USUARIO_ID VARCHAR(80) CHARACTER SET UTF8 NOT NULL,
 NOME_AVALIADOR VARCHAR(150) CHARACTER SET UTF8 NOT NULL,
 NOME_CLINICA VARCHAR(150) CHARACTER SET UTF8 NOT NULL,
 NOME_SCRIPT VARCHAR(252) CHARACTER SET UTF8 NOT NULL,
 NUMERO_VERSAO VARCHAR(100) CHARACTER SET UTF8,
 NOTA_GERAL SMALLINT NOT NULL CHECK (NOTA_GERAL BETWEEN 1 AND 5),
 RECOMENDACAO VARCHAR(10) NOT NULL CHECK (RECOMENDACAO IN ('sim','talvez','nao')),
 FACILIDADE_USO SMALLINT CHECK (FACILIDADE_USO BETWEEN 1 AND 5),
 QUALIDADE_CONTEUDO SMALLINT CHECK (QUALIDADE_CONTEUDO BETWEEN 1 AND 5),
 COMPLETUDE SMALLINT CHECK (COMPLETUDE BETWEEN 1 AND 5),
 APARENCIA SMALLINT CHECK (APARENCIA BETWEEN 1 AND 5),
 UTILIDADE_CLINICA SMALLINT CHECK (UTILIDADE_CLINICA BETWEEN 1 AND 5),
 TITULO VARCHAR(150) CHARACTER SET UTF8,
 COMENTARIO VARCHAR(1000) CHARACTER SET UTF8,
 CRIADO_EM TIMESTAMP NOT NULL,
 ATUALIZADO_EM TIMESTAMP NOT NULL,
 SITUACAO VARCHAR(15) DEFAULT 'nova' NOT NULL CHECK (SITUACAO IN ('nova','em_analise','concluida')),
 VISIVEL SMALLINT DEFAULT 1 NOT NULL CHECK (VISIVEL IN (0,1)),
 CONSTRAINT CK_AVALIACAO_VERSAO CHECK (VERSAO_CHAVE = COALESCE(CODVERSAO,0)),
 CONSTRAINT UQ_SCRIPT_AVALIACAO UNIQUE (IDENTIDADE,CODSCRIPTLAUDO,VERSAO_CHAVE)
);
CREATE INDEX IX_AVALIACAO_SCRIPT ON SCRIPT_AVALIACAO(CODSCRIPTLAUDO,CODVERSAO,VISIVEL);
CREATE INDEX IX_AVALIACAO_DATA ON SCRIPT_AVALIACAO(ATUALIZADO_EM);
CREATE TABLE SCRIPT_AVALIACAO_EVENTO (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 AVALIACAO_ID BIGINT NOT NULL REFERENCES SCRIPT_AVALIACAO(ID),
 TIPO VARCHAR(20) NOT NULL,
 AUTOR VARCHAR(240) CHARACTER SET UTF8 NOT NULL,
 CODUSUARIO INTEGER,
 DATA_EVENTO TIMESTAMP NOT NULL,
 ANTES BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
 DEPOIS BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
 OBSERVACAO VARCHAR(2000) CHARACTER SET UTF8
);
CREATE INDEX IX_AVALIACAO_EVENTO ON SCRIPT_AVALIACAO_EVENTO(AVALIACAO_ID,ID);
