-- Assistente: migracao repetivel, consumida pelo migrador em blocos NEXT.
-- Nativos permanecem NULL. Somente a origem Conteudos gera codigos MOD-.
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME='SCRIPTLAUDO' AND RDB$FIELD_NAME='CODUNIVERSAL')) THEN
    EXECUTE STATEMENT 'ALTER TABLE SCRIPTLAUDO ADD CODUNIVERSAL VARCHAR(24) CHARACTER SET ASCII';
END
-- NEXT
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_CONSTRAINTS WHERE RDB$CONSTRAINT_NAME='UNQ_SCRIPTLAUDO_CODUNIVERSAL')) THEN
    EXECUTE STATEMENT 'ALTER TABLE SCRIPTLAUDO ADD CONSTRAINT UNQ_SCRIPTLAUDO_CODUNIVERSAL UNIQUE (CODUNIVERSAL)';
END
-- NEXT
CREATE OR ALTER EXCEPTION EX_ASS_CODUNIVERSAL 'Codigo universal imutavel; a atribuicao inicial deve vir da publicacao de Conteudos.'
-- NEXT
CREATE OR ALTER TRIGGER CON_SCRIPT_CODUNIVERSAL FOR SCRIPTLAUDO
ACTIVE BEFORE INSERT OR UPDATE POSITION 1
AS
BEGIN
  IF (UPDATING AND OLD.CODUNIVERSAL IS NOT NULL AND NEW.CODUNIVERSAL IS DISTINCT FROM OLD.CODUNIVERSAL) THEN
    EXCEPTION EX_ASS_CODUNIVERSAL;
  IF (NEW.CODUNIVERSAL IS NOT NULL AND
      (INSERTING OR OLD.CODUNIVERSAL IS NULL) AND
      RDB$GET_CONTEXT('USER_TRANSACTION', 'PUBLICACAO') IS DISTINCT FROM '1') THEN
    EXCEPTION EX_ASS_CODUNIVERSAL;
END
