-- Migracao repetivel. Executar pelo migrador, com cadastros suspensos e backup.
-- Cada bloco separado pelo marcador NEXT e uma instrucao completa para o Firebird.
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME='SCRIPTLAUDO' AND RDB$FIELD_NAME='CODUNIVERSAL')) THEN
    EXECUTE STATEMENT 'ALTER TABLE SCRIPTLAUDO ADD CODUNIVERSAL VARCHAR(24) CHARACTER SET ASCII';
  IF (NOT EXISTS(SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME='GEN_SCRIPTLAUDO_UNIVERSAL')) THEN
    EXECUTE STATEMENT 'CREATE SEQUENCE GEN_SCRIPTLAUDO_UNIVERSAL';
END
-- NEXT
EXECUTE BLOCK AS
DECLARE COD INTEGER;
DECLARE NUMERO VARCHAR(20);
BEGIN
  FOR SELECT CODSCRIPTLAUDO FROM SCRIPTLAUDO WHERE CODUNIVERSAL IS NULL ORDER BY CODSCRIPTLAUDO INTO :COD DO
  BEGIN
    NUMERO = CAST(NEXT VALUE FOR GEN_SCRIPTLAUDO_UNIVERSAL AS VARCHAR(20));
    UPDATE SCRIPTLAUDO SET CODUNIVERSAL = 'MOD-' || CASE WHEN CHAR_LENGTH(:NUMERO)<6 THEN LPAD(:NUMERO,6,'0') ELSE :NUMERO END
      WHERE CODSCRIPTLAUDO=:COD;
  END
END
-- NEXT
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_CONSTRAINTS WHERE RDB$CONSTRAINT_NAME='UNQ_SCRIPTLAUDO_CODUNIVERSAL')) THEN
    EXECUTE STATEMENT 'ALTER TABLE SCRIPTLAUDO ADD CONSTRAINT UNQ_SCRIPTLAUDO_CODUNIVERSAL UNIQUE (CODUNIVERSAL)';
  IF (EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME='SCRIPTLAUDO' AND RDB$FIELD_NAME='CODUNIVERSAL' AND COALESCE(RDB$NULL_FLAG,0)=0)) THEN
    EXECUTE STATEMENT 'ALTER TABLE SCRIPTLAUDO ALTER CODUNIVERSAL SET NOT NULL';
END
-- NEXT
CREATE OR ALTER EXCEPTION EX_SCRIPT_CODIGO_IMUTAVEL 'O codigo universal do modelo nao pode ser alterado.'
-- NEXT
CREATE OR ALTER TRIGGER SCRIPTLAUDO_CODUNIVERSAL FOR SCRIPTLAUDO
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
DECLARE NUMERO VARCHAR(20);
BEGIN
  IF (INSERTING) THEN
  BEGIN
    NUMERO = CAST(NEXT VALUE FOR GEN_SCRIPTLAUDO_UNIVERSAL AS VARCHAR(20));
    NEW.CODUNIVERSAL = 'MOD-' || CASE WHEN CHAR_LENGTH(NUMERO)<6 THEN LPAD(NUMERO,6,'0') ELSE NUMERO END;
  END
  ELSE IF (NEW.CODUNIVERSAL IS DISTINCT FROM OLD.CODUNIVERSAL) THEN
    EXCEPTION EX_SCRIPT_CODIGO_IMUTAVEL;
END
